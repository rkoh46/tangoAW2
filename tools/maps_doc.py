#!/usr/bin/env python3
"""Regenerates docs/MAPS.md from the audit example (needs the AW2 ROM and, for the pack's tables, the Dual Strike .nds).

usage: tools/maps_doc.py <AW2 rom> <Dual Strike .nds>   (build first: cargo build --release -p tango-gamesupport-aw2 --example aw2_map_audit)"""
import os, subprocess, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
exe = os.path.join(root, "target/release/examples/aw2_map_audit")
rom, nds = sys.argv[1], sys.argv[2]


def audit(pack, *flags):
    env = dict(os.environ)
    if pack:
        env["TANGOAW2_DS_ROM"] = nds
    out = subprocess.run([exe, rom, *flags], env=env, capture_output=True, text=True)
    if out.returncode != 0 and "--md" in flags:
        sys.exit("audit failed: " + out.stderr[-500:])
    return out.stdout.strip()


plain, pack = audit(False, "--md"), audit(True, "--md")
src_plain, src_pack = audit(False, "--sources"), audit(True, "--sources")
doc = f"""# Map pool

Every map a player-count list can show, with its armies **counted from the map data** (the owners of its property
tiles and of the units placed on it), not from AW2's labels. Generated by `tools/maps_doc.py <AW2 rom> <Dual Strike
.nds>` from the example `aw2_map_audit` (which exits 1 when a map's data disagrees with its header). A unit test
(`five_map::tests::every_map_has_the_armies_it_is_listed_for`) checks tangoAW2's own maps the same way.

## The lists

Every map is in exactly one of eight tabs, by the number of players it has and whether it is pre-deployed:
"2P", "2P Predeploy", "3P", "3P Predeploy", "4P", "4P Predeploy", "5P", "5P Predeploy" ("NP - Predeploy" is two
letters too wide for the game's tab box). A tab with no map is skipped (Left/Right passes over it).

- **Online** (a room of N players): its two tabs, "NP" and "NP Predeploy".
- **Offline Versus**: the eight tabs, on the game's tab slots 2..9. SELECT swaps them for AW2's own lists (Classic,
  Vs. Maps, Pre-Deployed, 3P Maps, 4P Maps, War Room, Design Maps and tangoAW2's 5P Maps) and back; the choice is
  kept for the session. (With the Dual Strike pack, SELECT on a 2P Dual Strike map keeps marking the second front.)
  War Room mode itself is unchanged: its list and scoring are as before, and its maps are also in the lists above.

**Pre-deployed** means the map starts with units placed **and has no production property**: no base, airport or
port, owned or neutral (a neutral one can be captured), so nobody can build units. A map with units placed and a base
is a plain map.

The 5P Predeploy tab has one map so far, Pentagon Atoll (five/pentagon.py generates it).

The game's list holds up to 110 maps per tab (it stopped at 50 and garbled its names past row 34 before).

## Counts by source

Source is where the map comes from: AW2's own maps by the tab AW2 lists them on (Classic, Vs. Maps, Pre-Deployed, 3P
Maps, 4P Maps, War Room), Dual Strike's (Versus or War Room, with the pack) or tangoAW2's. Each map is on one tab,
whatever its source. Every War Room map is listed (AW2 lists them on its Versus list too); none is left out.

### Without the Dual Strike pack

{src_plain}

### With the pack

{src_pack}


## Without the Dual Strike pack (AW2's own maps and tangoAW2's)

{plain}

## With the Dual Strike pack

{pack}
"""
open(os.path.join(root, "docs/MAPS.md"), "w").write(doc)
