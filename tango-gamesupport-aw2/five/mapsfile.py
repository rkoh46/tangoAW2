"""five/maps.txt as blocks (`map NAME` .. the blank line before the next `map`), so a generator can replace the maps it owns and leave every
other block alone. design_maps.py draws some of the maps; the rest (Pentagon Atoll from pentagon.py, hand-added maps) must survive a re-run."""
import re

HEADER = '# tangoAW2 5-army maps, generated by design_maps.py (legend in map.py).\n\n'


def split_blocks(text):
    """-> ordered list of (name, block text without trailing blank lines). Text before the first `map` line is dropped."""
    blocks, cur = [], None
    for line in text.split('\n'):
        m = re.match(r'map (.*)$', line)
        if m:
            cur = [m.group(1).strip(), [line]]
            blocks.append(cur)
        elif cur is not None:
            cur[1].append(line)
    return [(n, '\n'.join(ls).rstrip('\n')) for n, ls in blocks]


def merge(existing_text, generated_text):
    """Existing maps keep their place; a generated map of the same name replaces its block; generated maps not there yet are appended.
    Every existing map is kept (nothing generated can delete one)."""
    old = split_blocks(existing_text)
    new = dict(split_blocks(generated_text))
    out, seen = [], set()
    for name, block in old:
        out.append(new.get(name, block))
        seen.add(name)
    for name, block in split_blocks(generated_text):
        if name not in seen:
            out.append(block)
    return HEADER + '\n\n'.join(out) + '\n'
